#!/usr/bin/env python3
"""Writes src/system/device/tzrules.c: every IANA zone name with its POSIX TZ rule.

The rule is the footer of the zone's TZif file (version 2 and later), the
string the C library itself falls back on past the last transition the file
lists: "CET-1CEST,M3.5.0,M10.5.0/3" for Europe/Rome. Set as TZ, it makes
localtime() switch between standard time and daylight saving on the right day
with no zone files on the device.

The names include the links tzdata.zi lists (Europe/Kiev for Europe/Kyiv, and
so on), because a geolocation service may answer with either.

    python3 tools/tz_rules.py [/usr/share/zoneinfo] > src/system/device/tzrules.c

Run it again after a tzdata release that changes a rule.
"""

import os
import sys

SKIP_TOP = {"posix", "right", "Etc"}
SKIP_FILES = {"Factory", "localtime", "posixrules", "leapseconds", "leap-seconds.list", "tzdata.zi", "SECURITY"}


def footer(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"TZif" or data[4:5] not in (b"2", b"3", b"4"):
        return None
    lines = data.rstrip(b"\n").rsplit(b"\n", 1)
    if len(lines) != 2:
        return None
    rule = lines[1].decode("ascii")
    return rule or None


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    rules = {}
    for top, dirs, files in os.walk(root):
        rel_top = os.path.relpath(top, root)
        if rel_top.split(os.sep)[0] in SKIP_TOP:
            dirs[:] = []
            continue
        for name in files:
            if name in SKIP_FILES or name.endswith(".tab"):
                continue
            rel = os.path.normpath(os.path.join(rel_top, name))
            rule = footer(os.path.join(top, name))
            if rule:
                rules[rel] = rule
    # Etc/UTC and its kin, which the walk above leaves out with the rest of Etc.
    for name in ("Etc/UTC", "Etc/GMT", "UTC", "GMT"):
        path = os.path.join(root, name)
        if os.path.exists(path):
            rule = footer(path)
            if rule:
                rules[name] = rule

    version = "unknown"
    zi = os.path.join(root, "tzdata.zi")
    if os.path.exists(zi):
        with open(zi, encoding="utf-8") as f:
            for line in f:
                if line.startswith("# version "):
                    version = line.split()[-1]
                parts = line.split()
                if len(parts) == 3 and parts[0] == "L" and parts[1] in rules and parts[2] not in rules:
                    rules[parts[2]] = rules[parts[1]]

    names = sorted(rules)
    out = sys.stdout
    out.write("// Generated by tools/tz_rules.py from tzdata %s; run it again rather than\n" % version)
    out.write("// editing this file.\n\n")
    out.write('#include "tzrules.h"\n\n#include <stdlib.h>\n#include <string.h>\n\n')
    out.write("typedef struct {\n\tconst char *zone;\n\tconst char *rule;\n} tzrule_t;\n\n")
    out.write("// Sorted by zone, for bsearch().\n")
    out.write("static const tzrule_t RULES[] = {\n")
    for name in names:
        out.write('\t{"%s", "%s"},\n' % (name, rules[name]))
    out.write("};\n\n")
    out.write("static int compare(const void *key, const void *entry) { return strcmp(key, ((const tzrule_t *)entry)->zone); }\n\n")
    out.write("const char *tzrules_lookup(const char *zone) {\n")
    out.write("\tif (!zone || !zone[0]) {\n\t\treturn NULL;\n\t}\n")
    out.write("\tconst tzrule_t *found = bsearch(zone, RULES, sizeof(RULES) / sizeof(RULES[0]), sizeof(RULES[0]), compare);\n")
    out.write("\treturn found ? found->rule : NULL;\n}\n")


if __name__ == "__main__":
    main()
