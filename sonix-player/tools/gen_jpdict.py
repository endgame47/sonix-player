#!/usr/bin/env python3
"""Generate src/system/input/jpdict_data.c and jpdict_data.h.

The input is the default dictionary of lv_ime_jp_lite.c (lv_ime_jp_lite_def_dict),
which embeds SKK-JISYO.S. Only the dictionary is read; the code around it is not
used. The generated files are committed, so an ordinary build needs no Python.

    python3 tools/gen_jpdict.py path/to/lv_ime_jp_lite.c
    python3 tools/gen_jpdict.py --check path/to/lv_ime_jp_lite.c

--check writes nothing and fails when the committed files differ from what the
script makes.

The exact upstream is written into the notice at the top of jpdict_data.c: the
repository and branch, the commit (UPSTREAM_COMMIT below) and the SHA-256 of the
lv_ime_jp_lite.c that was read, so that the data can be reproduced.
"""

import argparse
import hashlib
import re
import sys
from pathlib import Path

# Where lv_ime_jp_lite.c comes from: a fork of LVGL with the Japanese IME added,
# which the simulator project https://github.com/fukuen/lv_port_pc_vscode (branch
# feat/ime-jp) uses as its lvgl submodule. UPSTREAM_COMMIT is the commit of the
# fork that the file was taken from.
UPSTREAM_REPO = "https://github.com/fukuen/lvgl"
UPSTREAM_COMMIT = "fbe7dc6c76b4b53b847afba17061d3bca5e7eb14"

OUT_DIR = Path(__file__).resolve().parent.parent / "src" / "system" / "input"

HEADER = """\
/*
 * jpdict_data.c: the dictionary of Japanese readings and their kanji.
 *
 * Generated by tools/gen_jpdict.py from the default dictionary of lv_ime_jp_lite.c.
 * Do not edit.
 *
 * Upstream:
{upstream}
 *
 * The notices that follow are those at the top of lv_ime_jp_lite.c, copied as they
 * are there: they cover the dictionary below and the way it is searched.
 */
"""

ENTRY_RE = re.compile(r'\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*\}')


def read_dictionary(path):
    """The (key, candidates) pairs of lv_ime_jp_lite_def_dict, in file order."""
    text = path.read_text(encoding="utf-8")
    start = text.index("lv_ime_jp_lite_def_dict[] = {")
    end = text.index("};", start)
    pairs = []
    for key, value in ENTRY_RE.findall(text[start:end]):
        # "/a/b/c/" -> "a/b/c"
        pairs.append((key, value.strip("/")))
    return pairs


def c_string_lines(items):
    for item in items:
        if '"' in item or "\\" in item:
            sys.exit("unexpected quote or backslash in %r" % item)
    return "".join('\t"%s" "\\0"\n' % item for item in items)


def read_notices(text):
    """The license comments at the top of lv_ime_jp_lite.c, as they are there.

    Every block comment before the first #include that carries a copyright line.
    They are copied word for word, so that a source with other notices
    (another dictionary, another license) gives other notices here.
    """
    top = text[: text.index("#include")]
    notices = []
    for block in re.findall(r"/\*.*?\*/", top, flags=re.S):
        if "Copyright" not in block:
            continue
        lines = [line.rstrip() for line in block.replace("\r\n", "\n").split("\n")]
        notices.append("\n".join(lines))
    if not notices:
        sys.exit("no license notice found at the top of the source")
    out = "\n\n".join(notices) + "\n"
    if not out.isascii():
        sys.exit("the notices are not ASCII: comments in this repository are")
    return out


def upstream_text(source_bytes):
    lines = [UPSTREAM_REPO]
    if UPSTREAM_COMMIT:
        lines.append("commit " + UPSTREAM_COMMIT)
    lines.append("lv_ime_jp_lite.c, SHA-256 " + hashlib.sha256(source_bytes).hexdigest())
    return "\n".join(" *   " + line for line in lines)


def build(pairs, upstream, notices):
    # Keys are sorted bytewise (a kana, then that kana plus a letter, then that
    # kana plus another kana), which is what the bisection of the first kana in
    # jpdict.c relies on. A key given twice keeps its last list.
    merged = {}
    for key, cands in pairs:
        merged[key] = cands
    keys = sorted(merged, key=lambda k: k.encode("utf-8"))

    key_off, offset = {}, 0
    for key in keys:
        key_off[key] = offset
        offset += len(key.encode("utf-8")) + 1
    keys_size = offset

    val_off, vals, offset = {}, [], 0
    for key in keys:
        cands = merged[key]
        if cands not in val_off:
            val_off[cands] = offset
            vals.append(cands)
            offset += len(cands.encode("utf-8")) + 1
    vals_size = offset
    if keys_size > 0xFFFF or vals_size > 0xFFFF or len(keys) > 0xFFFF:
        sys.exit("a string table or the entry table no longer fits 16-bit offsets: keys %d, values %d, entries %d"
                 % (keys_size, vals_size, len(keys)))

    heads = []
    for i, key in enumerate(keys):
        cp = ord(key[0])
        if heads and heads[-1][0] == cp:
            heads[-1][2] += 1
        else:
            heads.append([cp, i, 1])

    out = [HEADER.format(upstream=upstream), "\n", notices, "\n"]
    out.append('#include "jpdict_data.h"\n\n')
    out.append("// clang-format off\n\n")
    out.append("// Keys: a hiragana reading, plus a lower-case okurigana consonant for verbs and\n")
    out.append('// adjectives: the key "<kana>k" stands for that kana followed by one of the five\n')
    out.append("// kana of the k row (see OKURI in jpdict.c). Each key ends in a NUL.\n")
    out.append("const char JPDICT_KEYS[%d] =\n" % keys_size)
    out.append(c_string_lines(keys))
    out.append(";\n\n")
    out.append('// Candidates, "/" between them, a NUL at the end. Identical lists are stored once.\n')
    out.append("const char JPDICT_VALS[%d] =\n" % vals_size)
    out.append(c_string_lines(vals))
    out.append(";\n\n")
    out.append("const jpdict_entry_t JPDICT_ENTRIES[JPDICT_ENTRY_COUNT] = {\n")
    cells = ["{%d, %d}" % (key_off[k], val_off[merged[k]]) for k in keys]
    for i in range(0, len(cells), 4):
        out.append("\t" + ", ".join(cells[i:i + 4]) + ",\n")
    out.append("};\n\n")
    out.append("const jpdict_head_t JPDICT_HEADS[JPDICT_HEAD_COUNT] = {\n")
    for cp, first, count in heads:
        out.append("\t{0x%04X, %d, %d},\n" % (cp, first, count))
    out.append("};\n\n// clang-format on\n")
    data_c = "".join(out)

    data_h = """\
// Generated by tools/gen_jpdict.py from the default dictionary of lv_ime_jp_lite.c.
// Do not edit. See the notice at the top of jpdict_data.c.
#ifndef JPDICT_DATA_H
#define JPDICT_DATA_H

#include <stdint.h>

// clang-format off

#define JPDICT_ENTRY_COUNT %d
#define JPDICT_HEAD_COUNT %d

typedef struct {
	uint16_t key; // offset into JPDICT_KEYS
	uint16_t val; // offset into JPDICT_VALS
} jpdict_entry_t;

typedef struct {
	uint16_t cp;    // the head kana, as a code point
	uint16_t first; // its first entry
	uint16_t count;
} jpdict_head_t;

extern const char JPDICT_KEYS[%d];
extern const char JPDICT_VALS[%d];
extern const jpdict_entry_t JPDICT_ENTRIES[JPDICT_ENTRY_COUNT];
extern const jpdict_head_t JPDICT_HEADS[JPDICT_HEAD_COUNT];

// clang-format on

#endif
""" % (len(keys), len(heads), keys_size, vals_size)
    return data_c, data_h


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", type=Path, help="lv_ime_jp_lite.c")
    ap.add_argument("--check", action="store_true", help="write nothing; fail if the committed files differ")
    args = ap.parse_args()

    if not UPSTREAM_COMMIT:
        print("warning: UPSTREAM_COMMIT is empty; the notice names the file's SHA-256 only", file=sys.stderr)
    raw = args.source.read_bytes()
    text = raw.decode("utf-8")
    data_c, data_h = build(read_dictionary(args.source), upstream_text(raw), read_notices(text))
    targets = {OUT_DIR / "jpdict_data.c": data_c, OUT_DIR / "jpdict_data.h": data_h}
    bad = 0
    for path, content in targets.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                print("differs: %s" % path)
                bad += 1
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
            print("wrote %s" % path)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
